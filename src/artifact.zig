//! The output directory (design/prototype.md, "The output directory"): its
//! layout, `artifact.json`, and the `run` script, specified in
//! spec/output.md.
//!
//! `read` came first, from W8, for pack and export on a build's output;
//! `write` is the build's.

const std = @import("std");
const types = @import("types.zig");

pub const json_file = "artifact.json";

pub const ReadError = error{ NoArtifact, BadArtifact, UnsupportedVersion, OutOfMemory } || std.Io.Dir.ReadFileAllocError;

/// Reads `OUT/artifact.json`, for pack, export, and run on a build's
/// output. Fields a later h9x adds are ignored. error.NoArtifact if there
/// is none.
pub fn read(arena: std.mem.Allocator, io: std.Io, out_dir: []const u8) ReadError!types.Artifact {
    const path = try std.fs.path.join(arena, &.{ out_dir, json_file });
    const text = std.Io.Dir.cwd().readFileAlloc(io, path, arena, .limited(16 << 20)) catch |e| switch (e) {
        error.FileNotFound, error.NotDir => return error.NoArtifact,
        else => |x| return x,
    };
    return parse(arena, text);
}

/// artifact.json's text, parsed.
pub fn parse(arena: std.mem.Allocator, text: []const u8) error{ BadArtifact, UnsupportedVersion, OutOfMemory }!types.Artifact {
    const a = std.json.parseFromSliceLeaky(types.Artifact, arena, text, .{
        .ignore_unknown_fields = true,
        .allocate = .alloc_always,
    }) catch |e| switch (e) {
        error.OutOfMemory => return error.OutOfMemory,
        else => return error.BadArtifact,
    };
    if (a.version != types.Artifact.current_version) return error.UnsupportedVersion;
    return a;
}

/// A host path as artifact.json writes it: `$cache/...` under the cache,
/// relative under the output directory, and absolute otherwise.
pub fn storedPath(arena: std.mem.Allocator, out_dir: []const u8, cache_dir: []const u8, p: []const u8) error{OutOfMemory}![]const u8 {
    if (below(p, cache_dir)) |rest| return std.fmt.allocPrint(arena, "$cache/{s}", .{rest});
    if (below(p, out_dir)) |rest| return arena.dupe(u8, rest);
    return p;
}

fn below(p: []const u8, dir: []const u8) ?[]const u8 {
    const d = std.mem.trimEnd(u8, dir, "/");
    if (p.len > d.len + 1 and std.mem.startsWith(u8, p, d) and p[d.len] == '/') return p[d.len + 1 ..];
    return null;
}

/// Writes `OUT/artifact.json`, through a temporary file, so a reader never
/// sees half of one.
pub fn write(arena: std.mem.Allocator, io: std.Io, out_dir: []const u8, art: types.Artifact) !void {
    var w: std.Io.Writer.Allocating = .init(arena);
    try std.json.Stringify.value(art, .{ .whitespace = .indent_2 }, &w.writer);
    try w.writer.writeByte('\n');
    const tmp = try std.fs.path.join(arena, &.{ out_dir, json_file ++ ".tmp" });
    const cwd = std.Io.Dir.cwd();
    try cwd.writeFile(io, .{ .sub_path = tmp, .data = w.written() });
    try std.Io.Dir.rename(cwd, tmp, cwd, try std.fs.path.join(arena, &.{ out_dir, json_file }), io);
}

/// `OUT/run`: runs the app with `h9x run` on the output directory.
/// Arguments replace the start command.
pub const run_script =
    \\#!/bin/sh
    \\# Generated by h9x: runs the app on h9 from its layers, with h9x run.
    \\# Arguments replace the start command. H9X names the h9x to use.
    \\here=$(cd "$(dirname "$0")" && pwd)
    \\if [ $# -gt 0 ]; then exec "${H9X:-h9x}" run "$here" -- "$@"; fi
    \\exec "${H9X:-h9x}" run "$here"
    \\
;

pub fn writeRun(arena: std.mem.Allocator, io: std.Io, out_dir: []const u8) !void {
    const p = try std.fs.path.join(arena, &.{ out_dir, "run" });
    var f = try std.Io.Dir.cwd().createFile(io, p, .{ .permissions = .executable_file });
    defer f.close(io);
    var buf: [1024]u8 = undefined;
    var fw = f.writer(io, &buf);
    try fw.interface.writeAll(run_script);
    try fw.interface.flush();
}

/// A path in artifact.json as a host path: `$cache/...` under the cache,
/// a relative one under the output directory, and an absolute one as it
/// is.
pub fn resolvePath(arena: std.mem.Allocator, out_dir: []const u8, cache_dir: []const u8, p: []const u8) error{OutOfMemory}![]const u8 {
    const prefix = "$cache/";
    if (std.mem.startsWith(u8, p, prefix)) return std.fs.path.join(arena, &.{ cache_dir, p[prefix.len..] });
    if (std.fs.path.isAbsolute(p)) return p;
    return std.fs.path.join(arena, &.{ out_dir, p });
}

test storedPath {
    var a: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer a.deinit();
    const ar = a.allocator();
    try std.testing.expectEqualStrings("$cache/roots/base-k", try storedPath(ar, "/o", "/c/", "/c/roots/base-k"));
    try std.testing.expectEqualStrings("layers/app", try storedPath(ar, "/o", "/c", "/o/layers/app"));
    try std.testing.expectEqualStrings("/elsewhere", try storedPath(ar, "/o", "/c", "/elsewhere"));
}

test "write, then read" {
    var a: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer a.deinit();
    const ar = a.allocator();
    var tmp = std.testing.tmpDir(.{});
    defer tmp.cleanup();
    const dir = try tmp.dir.realPathFileAlloc(std.testing.io, ".", ar);
    try write(ar, std.testing.io, dir, .{
        .arch = .amd64,
        .base = .{ .path = "$cache/roots/base-k", .packages = &.{"glibc"} },
        .layers = &.{.{ .name = .app, .key = "a", .path = "layers/app" }},
        .env = &.{"PATH=/bin"},
        .start = "node server.js",
    });
    const art = try read(ar, std.testing.io, dir);
    try std.testing.expectEqualStrings("node server.js", art.start.?);
    try std.testing.expectEqual(types.LayerName.app, art.layers[0].name);
}

test parse {
    var a: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer a.deinit();
    const art = try parse(a.allocator(),
        \\{"version":1,"arch":"amd64","base":{"path":"$cache/roots/base-k","packages":["glibc"]},
        \\ "layers":[{"name":"runtime","key":"r","path":"$cache/runtimes/r"},{"name":"app","key":"a","path":"layers/app"}],
        \\ "env":["PATH=/bin"],"start":"node server.js","cwd":"/app","later":true}
    );
    try std.testing.expectEqual(types.LayerName.app, art.layers[1].name);
    try std.testing.expectEqualStrings("/c/runtimes/r", try resolvePath(a.allocator(), "/o", "/c", art.layers[0].path));
    try std.testing.expectEqualStrings("/o/layers/app", try resolvePath(a.allocator(), "/o", "/c", art.layers[1].path));
    try std.testing.expectError(error.UnsupportedVersion, parse(a.allocator(), "{\"version\":2,\"arch\":\"amd64\",\"base\":{\"path\":\"\",\"packages\":[]},\"layers\":[],\"env\":[],\"start\":null}"));
}
